func CharWidth(r rune) int {
	if r == '\uFE0F' || combiningMarks.contains(r) {
		return 0
	}
	if eastAsianWide.contains(r) {
		return 2
	}

	if (r >= 0x2600 && r <= 0x27BF) || (r >= 0x1F300 && r <= 0x1FAFF) {
		return 2
	}
	return 1
}

func DispWidth(text string) int {
	w := 0
	for _, r := range text {
		w += CharWidth(r)
	}
	return w
}

const (
	AlignLeft  = "left"
	AlignRight = "right"
)

func Pad(text string, width int, align string) string {
	s := text
	used := DispWidth(s)
	if used > width {

		return s
	}
	fill := strings.Repeat(" ", width-used)
	if align == AlignRight {
		return fill + s
	}
	return s + fill
}

func Repeat(ch string, n int) string {
	if n <= 0 {
		return ""
	}
	return strings.Repeat(ch, n)
}
