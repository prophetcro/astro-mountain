package report

import "strings"

type rangeTable [][2]rune

func (t rangeTable) contains(r rune) bool {
	lo, hi := 0, len(t)-1
	for lo <= hi {
		mid := (lo + hi) / 2
		switch {
		case r < t[mid][0]:
			hi = mid - 1
		case r > t[mid][1]:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}

